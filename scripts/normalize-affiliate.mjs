import fs from 'node:fs';
import path from 'node:path';

const readJson = (file) => fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
const offerDir = 'data/offers';
const offers = fs.readdirSync(offerDir)
  .filter((name) => name.endsWith('.json'))
  .map((name) => readJson(path.join(offerDir, name)));
const offerByProgram = new Map(
  offers.filter((offer) => offer?.asp === 'valuecommerce' && offer?.aspProgramId != null)
    .map((offer) => [String(offer.aspProgramId), offer.id])
);

function normalizeA8Status(value) {
  const text = String(value || '').replace(/\s/g, '');
  if (/キャンセル|否認|拒否/.test(text)) return 'rejected';
  if (/未確定|発生|保留/.test(text)) return 'pending';
  if (/支払|振込/.test(text)) return 'paid';
  if (/確定|承認/.test(text)) return 'approved';
  return 'unknown';
}
function normalizeVcStatus(value) {
  return ({ P: 'pending', A: 'approved', C: 'rejected', I: 'paid' })[String(value || '').toUpperCase()] || 'unknown';
}
function parseVcTracking(value) {
  // Reserved for links generated by an officially supported VC mechanism that
  // explicitly carries vcptn. We never append vcptn to arbitrary affiliate URLs.
  const text = String(value || '');
  if (!text.startsWith('ashp1~')) return {};
  const [, pageId = '', offerId = '', ctaId = '', positionId = ''] = text.split('~');
  return { pageId, offerId, ctaId, positionId };
}

const events = [];
const a8 = readJson('data/affiliate/a8-latest.json');
for (const [index, row] of (a8?.rows || []).entries()) {
  events.push({
    id: `a8:${index}:${row.occurredAt || ''}`,
    asp: 'a8',
    occurredAt: row.occurredAt || null,
    status: normalizeA8Status(row.status),
    amountYen: Number(row.amountYen || 0),
    pageId: row.pageId || null,
    offerId: row.offerId || null,
    ctaId: row.ctaId || null,
    positionId: row.positionId || null,
    programId: null,
    programName: null
  });
}

const vc = readJson('data/affiliate/valuecommerce-latest.json');
for (const row of (vc?.rows || [])) {
  const tracked = parseVcTracking(row.vcptn);
  events.push({
    id: `valuecommerce:${row.transactionOid}`,
    asp: 'valuecommerce',
    occurredAt: row.orderDate || null,
    status: normalizeVcStatus(row.approvalStatus),
    amountYen: Number(row.affilPayment || 0),
    pageId: tracked.pageId || null,
    offerId: tracked.offerId || offerByProgram.get(String(row.programOid)) || null,
    ctaId: tracked.ctaId || null,
    positionId: tracked.positionId || null,
    programId: row.programOid ?? null,
    programName: row.programName ?? null
  });
}

const totals = { events: events.length, pendingYen: 0, confirmedYen: 0, rejectedYen: 0, unknownYen: 0 };
for (const event of events) {
  if (event.status === 'pending') totals.pendingYen += event.amountYen;
  else if (event.status === 'approved' || event.status === 'paid') totals.confirmedYen += event.amountYen;
  else if (event.status === 'rejected') totals.rejectedYen += event.amountYen;
  else totals.unknownYen += event.amountYen;
}

const groups = new Map();
for (const event of events) {
  const key = [event.asp,event.pageId || '',event.offerId || '',event.ctaId || '',event.positionId || '',event.programId || ''].join('|');
  const current = groups.get(key) || {
    asp: event.asp, pageId: event.pageId, offerId: event.offerId, ctaId: event.ctaId,
    positionId: event.positionId, programId: event.programId, programName: event.programName,
    events: 0, pendingYen: 0, confirmedYen: 0, rejectedYen: 0
  };
  current.events += 1;
  if (event.status === 'pending') current.pendingYen += event.amountYen;
  else if (event.status === 'approved' || event.status === 'paid') current.confirmedYen += event.amountYen;
  else if (event.status === 'rejected') current.rejectedYen += event.amountYen;
  groups.set(key, current);
}

const output = {
  normalizedAt: new Date().toISOString(),
  sources: { a8ImportedAt: a8?.importedAt || null, valuecommerceFetchedAt: vc?.fetchedAt || null },
  totals,
  events,
  paths: [...groups.values()].sort((a, b) => (b.confirmedYen - a.confirmedYen) || (b.pendingYen - a.pendingYen))
};
fs.mkdirSync('data/affiliate', { recursive: true });
fs.writeFileSync('data/affiliate/normalized-latest.json', JSON.stringify(output, null, 2));
console.log(`Normalized ${events.length} affiliate events; confirmed ¥${totals.confirmedYen}, pending ¥${totals.pendingYen}.`);
